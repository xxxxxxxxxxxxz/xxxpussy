-- Confirm your provider permits the intended content before using this setup.
-- Create an administrator account and disable public sign-ups first.
-- Do not put a service-role key in website files.

create table if not exists public.gallery_items (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 100),
  category text not null check (char_length(category) between 1 and 60),
  image_path text not null,
  created_at timestamptz not null default now()
);

alter table public.gallery_items enable row level security;

create policy "Public can view gallery items"
on public.gallery_items for select
to anon, authenticated using (true);

create policy "Authenticated users can add gallery items"
on public.gallery_items for insert
to authenticated with check (auth.uid() is not null);

create policy "Authenticated users can update gallery items"
on public.gallery_items for update
to authenticated
using (auth.uid() is not null)
with check (auth.uid() is not null);

create policy "Authenticated users can delete gallery items"
on public.gallery_items for delete
to authenticated using (auth.uid() is not null);

-- Create a PUBLIC storage bucket named gallery-images.
-- Disable public sign-ups after creating your own admin account.
create policy "Public can view gallery files"
on storage.objects for select
to anon, authenticated using (bucket_id = 'gallery-images');

create policy "Authenticated users can upload gallery files"
on storage.objects for insert
to authenticated
with check (bucket_id = 'gallery-images' and auth.uid() is not null);

create policy "Authenticated users can update gallery files"
on storage.objects for update
to authenticated
using (bucket_id = 'gallery-images' and auth.uid() is not null)
with check (bucket_id = 'gallery-images' and auth.uid() is not null);

create policy "Authenticated users can delete gallery files"
on storage.objects for delete
to authenticated
using (bucket_id = 'gallery-images' and auth.uid() is not null);
